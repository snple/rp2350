macro_rules! impl_bus_priority {
    ($(($name:ident, $set:ident, $clr:ident, $get:ident)),+ $(,)?) => {
        paste! {
            $(
                impl Busctrl {
                    #[doc = concat!("Set ", stringify!($name), " to high priority.")]
                    #[inline]
                    pub fn [<set_ $name _high_priority>](&self, high: bool) {
                        if high {
                            self.regs.bus_priority.$set();
                        } else {
                            self.regs.bus_priority.$clr();
                        }
                    }

                    #[doc = concat!("Check if ", stringify!($name), " has high priority.")]
                    #[inline]
                    pub fn [<is_ $name _high_priority>](&self) -> bool {
                        self.regs.bus_priority.$get()
                    }
                }
            )+
        }
    };
}

impl_bus_priority!(
    (proc0, set_proc0, clr_proc0, proc0),
    (proc1, set_proc1, clr_proc1, proc1),
    (dma_r, set_dma_r, clr_dma_r, dma_r),
    (dma_w, set_dma_w, clr_dma_w, dma_w),
);

macro_rules! impl_perf_counters {
    ($($n:literal),+ $(,)?) => {
        paste! {
            $(
                impl Busctrl {
                    #[doc = concat!("Get performance counter ", $n, " value.")]
                    #[inline]
                    pub fn [<perfctr $n>](&self) -> u32 {
                        self.regs.[<perfctr $n>].[<perfctr $n>]()
                    }

                    #[doc = concat!("Clear performance counter ", $n, ".")]
                    #[inline]
                    pub fn [<clear_perfctr $n>](&self) {
                        self.regs.[<perfctr $n>].[<write_perfctr $n>](0);
                    }

                    #[doc = concat!("Set performance counter ", $n, " event selection.")]
                    #[inline]
                    pub fn [<set_perfsel $n>](&self, event: PerfEvent) {
                        self.regs.[<perfsel $n>].[<write_perfsel $n>](event as u32);
                    }

                    #[doc = concat!("Get performance counter ", $n, " event selection.")]
                    #[inline]
                    pub fn [<perfsel $n>](&self) -> u32 {
                        self.regs.[<perfsel $n>].[<perfsel $n>]()
                    }
                }
            )+
        }
    };
}

impl_perf_counters!(0, 1, 2, 3);
